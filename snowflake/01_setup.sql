USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS LOADER_ROLE;
CREATE ROLE IF NOT EXISTS TRANSFORMER_ROLE;
CREATE ROLE IF NOT EXISTS ANALYST_ROLE;

GRANT ROLE LOADER_ROLE      TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER_ROLE TO ROLE SYSADMIN;
GRANT ROLE ANALYST_ROLE     TO ROLE SYSADMIN;

USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS LOADING_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS TRANSFORM_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS ANALYTICS_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

GRANT USAGE ON WAREHOUSE LOADING_WH   TO ROLE LOADER_ROLE;
GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE TRANSFORMER_ROLE;
GRANT USAGE ON WAREHOUSE ANALYTICS_WH TO ROLE ANALYST_ROLE;

CREATE DATABASE IF NOT EXISTS NYC_TAXI_DB;
CREATE SCHEMA   IF NOT EXISTS NYC_TAXI_DB.BRONZE;

GRANT USAGE ON DATABASE NYC_TAXI_DB TO ROLE LOADER_ROLE;
GRANT USAGE ON DATABASE NYC_TAXI_DB TO ROLE TRANSFORMER_ROLE;
GRANT USAGE ON DATABASE NYC_TAXI_DB TO ROLE ANALYST_ROLE;
GRANT CREATE SCHEMA ON DATABASE NYC_TAXI_DB TO ROLE TRANSFORMER_ROLE;

CREATE FILE FORMAT IF NOT EXISTS NYC_TAXI_DB.BRONZE.PARQUET_FORMAT
  TYPE = 'PARQUET'
  USE_LOGICAL_TYPE = TRUE;

CREATE STAGE IF NOT EXISTS NYC_TAXI_DB.BRONZE.RAW_STAGE
  FILE_FORMAT = NYC_TAXI_DB.BRONZE.PARQUET_FORMAT;

CREATE TABLE IF NOT EXISTS NYC_TAXI_DB.BRONZE.YELLOW_TRIPS_RAW (
  VENDORID              NUMBER,
  TPEP_PICKUP_DATETIME  TIMESTAMP_NTZ,
  TPEP_DROPOFF_DATETIME TIMESTAMP_NTZ,
  PASSENGER_COUNT       FLOAT,
  TRIP_DISTANCE         FLOAT,
  RATECODEID            FLOAT,
  STORE_AND_FWD_FLAG    VARCHAR,
  PULOCATIONID          NUMBER,
  DOLOCATIONID          NUMBER,
  PAYMENT_TYPE          NUMBER,
  FARE_AMOUNT           NUMBER(18,2),
  EXTRA                 NUMBER(18,2),
  MTA_TAX               NUMBER(18,2),
  TIP_AMOUNT            NUMBER(18,2),
  TOLLS_AMOUNT          NUMBER(18,2),
  IMPROVEMENT_SURCHARGE NUMBER(18,2),
  TOTAL_AMOUNT          NUMBER(18,2),
  CONGESTION_SURCHARGE  NUMBER(18,2),
  AIRPORT_FEE           NUMBER(18,2),
  CBD_CONGESTION_FEE    NUMBER(18,2),
  _SOURCE_FILE          VARCHAR,
  _LOADED_AT            TIMESTAMP_NTZ
);

GRANT USAGE ON SCHEMA NYC_TAXI_DB.BRONZE                       TO ROLE LOADER_ROLE;
GRANT USAGE ON FILE FORMAT NYC_TAXI_DB.BRONZE.PARQUET_FORMAT   TO ROLE LOADER_ROLE;
GRANT READ, WRITE ON STAGE NYC_TAXI_DB.BRONZE.RAW_STAGE        TO ROLE LOADER_ROLE;
GRANT INSERT, SELECT ON ALL TABLES    IN SCHEMA NYC_TAXI_DB.BRONZE TO ROLE LOADER_ROLE;
GRANT INSERT, SELECT ON FUTURE TABLES IN SCHEMA NYC_TAXI_DB.BRONZE TO ROLE LOADER_ROLE;

GRANT USAGE ON SCHEMA NYC_TAXI_DB.BRONZE                       TO ROLE TRANSFORMER_ROLE;
GRANT SELECT ON ALL TABLES    IN SCHEMA NYC_TAXI_DB.BRONZE     TO ROLE TRANSFORMER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA NYC_TAXI_DB.BRONZE     TO ROLE TRANSFORMER_ROLE;

USE ROLE TRANSFORMER_ROLE;

CREATE SCHEMA IF NOT EXISTS NYC_TAXI_DB.SILVER;
CREATE SCHEMA IF NOT EXISTS NYC_TAXI_DB.GOLD;

GRANT USAGE ON SCHEMA NYC_TAXI_DB.GOLD                         TO ROLE ANALYST_ROLE;
GRANT SELECT ON ALL TABLES    IN SCHEMA NYC_TAXI_DB.GOLD       TO ROLE ANALYST_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA NYC_TAXI_DB.GOLD       TO ROLE ANALYST_ROLE;
GRANT SELECT ON ALL VIEWS     IN SCHEMA NYC_TAXI_DB.GOLD       TO ROLE ANALYST_ROLE;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA NYC_TAXI_DB.GOLD       TO ROLE ANALYST_ROLE;

